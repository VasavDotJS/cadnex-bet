// Bundles the money Edge Function (src/money/edge.ts and everything it uses) into one file:
// supabase/functions/money/money.js. The function's index.ts imports it pinned to a commit.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const out = 'supabase/functions/money/money.js';
await build({
  entryPoints: ['src/money/edge.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: out,
  minify: true,
  legalComments: 'none',
  define: { 'process.env.CADNEX_FIXTURES': 'undefined' },
  external: ['node:*'],
  logLevel: 'warning',
});
const code = readFileSync(out, 'utf8');
writeFileSync(out, `// Generated by scripts/build-money.mjs from src/money. Do not edit by hand.\n${code}`);
console.log(`${out}: ${(code.length / 1024).toFixed(0)} KB`);
